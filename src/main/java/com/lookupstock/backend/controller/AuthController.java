

@RestController
@RequestMapping("/api/auth")
public class AuthController {

    UserManager userManager =
            PropertyFileUserManagerImpl.getPropertyFileUserManagerImpl("src/main/resources/Users.properties");

  @PostMapping(
        path = "/register",
        consumes = {MediaType.APPLICATION_JSON_VALUE, MediaType.APPLICATION_XML_VALUE}
    )
    @ResponseStatus(HttpStatus.OK)
    public TokenAnswer registerUser(@RequestBody LogIn logIn) {
        Logger myLogger = Logger.getLogger("UserRegistration");
        myLogger.info("Received a registration request for " + logIn.getEmail());

        String token = userManager.registerUser(logIn.getEmail(), logIn.getPassword());

        if ("USER-EXISTS".equals(token)) {
            return new TokenAnswer("This email is already registered.", 0);
        }
        if ("NO-FILE-ACCESS".equals(token)) {
            return new TokenAnswer("User data could not be accessed.", 0);
        }

        return new TokenAnswer(token, 1140);
    }
    
    @PostMapping(
            path = "/login",
            consumes = {MediaType.APPLICATION_JSON_VALUE, MediaType.APPLICATION_XML_VALUE}
    )
    @ResponseStatus(HttpStatus.OK)
    public TokenAnswer loginUser(@RequestBody LogIn logIn) {

        Logger myLogger = Logger.getLogger("UserLogIn");
        myLogger.info("Received a POST request on login with email " + logIn.getEmail());

        String token = userManager.logUserOn(logIn.getEmail(), logIn.getPassword());
        myLogger.info("Token generated by the system " + token);

        TokenAnswer myAnswer = new TokenAnswer(token, 1140);
        if (token.equals("NOT-FOUND")) myAnswer.setToken("We could not log you in.");
        if (token.equals("NO-FILE-ACCESS")) myAnswer.setToken("Our file system is cracked at the moment.");
        return myAnswer;
    }

    @DeleteMapping(
            path = "/logoff",
            consumes = {MediaType.APPLICATION_JSON_VALUE, MediaType.APPLICATION_XML_VALUE}
    )
    @ResponseStatus(HttpStatus.OK)
    public MessageAnswer logoffUser(@RequestBody Token token) {

        Logger myLogger = Logger.getLogger("UserLogOff");
        myLogger.info("Received a POST request on logon with token " + token.getToken());

        final boolean logUserOff = userManager.logUserOff(userManager.getUserFromToken(token.getToken()));
        myLogger.info("User logged off " + logUserOff);

        if (logUserOff) return new MessageAnswer("We logged you out.");
        return new MessageAnswer("We could not log you out.");
    }
}